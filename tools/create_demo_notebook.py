                    "class DirectionalPenaltyLoss(nn.Module):\n",
                    "    def __init__(self, penalty_weight=0.5, close_idx=3):\n",
                    "        super().__init__()\n",
                    "        self.mse = nn.MSELoss()\n",
                    "        self.penalty_weight = penalty_weight\n",
                    "        self.close_idx = close_idx\n",
                    "    def forward(self, pred, target, x_seq):\n",
                    "        mse_loss = self.mse(pred, target)\n",
                    "        y_prev = x_seq[:, -1, self.close_idx].unsqueeze(-1)\n",
                    "        dir_pred = pred - y_prev\n",
                    "        dir_true = target - y_prev\n",
                    "        penalty = torch.relu(-dir_pred * dir_true).mean()\n",
                    "        return mse_loss + self.penalty_weight * penalty\n",
                    "\n",
                    "def train_model(model, train_loader, val_loader, epochs=25, lr=0.001):\n",
                    "    model = model.to(device)\n",
                    "    criterion = DirectionalPenaltyLoss(penalty_weight=0.5, close_idx=close_idx)\n",
                    "    optimizer = torch.optim.AdamW(model.parameters(), lr=lr, weight_decay=1e-4)\n",
                    "    scheduler = torch.optim.lr_scheduler.ReduceLROnPlateau(optimizer, mode='min', factor=0.5, patience=5)\n",
                    "    \n",
                    "    history = {'train_loss': [], 'val_loss': []}\n",
                    "    best_val = float('inf')\n",
                    "    best_weights = None\n",
                    "    \n",
                    "    print(f\"\\n{'='*65}\\n BẮT ĐẦU HUẤN LUYỆN: {model.__class__.__name__}\\n{'='*65}\")\n",
                    "    for epoch in range(1, epochs + 1):\n",
                    "        model.train()\n",
                    "        t_loss = 0\n",
                    "        for bx, by in train_loader:\n",
                    "            bx, by = bx.to(device), by.to(device)\n",
                    "            optimizer.zero_grad()\n",
                    "            out = model(bx)\n",
                    "            loss = criterion(out, by, bx)\n",
                    "            loss.backward()\n",
                    "            optimizer.step()\n",
                    "            t_loss += loss.item() * len(bx)\n",
                    "        t_loss /= len(train_loader.dataset)\n",
                    "        \n",
                    "        model.eval()\n",
                    "        v_loss = 0\n",
                    "        with torch.no_grad():\n",
                    "            for bx, by in val_loader:\n",
