                    "# 1. Core Model: LSTM for Regression (Topic.png Core Requirement)\n",
                    "class VanillaLSTM(nn.Module):\n",
                    "    def __init__(self, input_dim, hidden_dim=64, num_layers=1, dropout=0.1):\n",
                    "        super().__init__()\n",
                    "        self.lstm = nn.LSTM(input_dim, hidden_dim, num_layers=num_layers, batch_first=True, dropout=dropout if num_layers > 1 else 0.0)\n",
                    "        self.fc = nn.Sequential(\n",
                    "            nn.Linear(hidden_dim, 32),\n",
                    "            nn.ReLU(),\n",
                    "            nn.Linear(32, 1)\n",
                    "        )\n",
                    "    def forward(self, x):\n",
                    "        out, (hn, _) = self.lstm(x)\n",
                    "        return self.fc(out[:, -1, :])\n",
                    "\n",
                    "# 2. Extension Model: 1D-CNN for Regression (Topic.png Compare CNN vs LSTM)\n",
                    "class VanillaCNN1D(nn.Module):\n",
                    "    def __init__(self, input_dim, num_filters=64, kernel_size=3):\n",
                    "        super().__init__()\n",
                    "        self.conv = nn.Sequential(\n",
                    "            nn.Conv1d(input_dim, num_filters, kernel_size=kernel_size, padding=kernel_size//2),\n",
                    "            nn.BatchNorm1d(num_filters),\n",
                    "            nn.ReLU(),\n",
                    "            nn.AdaptiveAvgPool1d(1)\n",
                    "        )\n",
                    "        self.fc = nn.Linear(num_filters, 1)\n",
                    "    def forward(self, x):\n",
                    "        # x: (B, L, D) -> (B, D, L)\n",
                    "        out = self.conv(x.permute(0, 2, 1))\n",
                    "        return self.fc(out.squeeze(-1))\n",
                    "\n",
                    "# 3. Proposed SOTA: CNN-BiLSTM-Self-Attention (Điểm Sáng NCKH)\n",
                    "class TemporalSelfAttention(nn.Module):\n",
                    "    def __init__(self, hidden_dim):\n",
                    "        super().__init__()\n",
                    "        self.attn = nn.Linear(hidden_dim, 1, bias=False)\n",
                    "    def forward(self, x):\n",
                    "        weights = torch.softmax(self.attn(x), dim=1)\n",
                    "        return (x * weights).sum(dim=1), weights\n",
                    "\n",
                    "class CNNBiLSTMAttention(nn.Module):\n",
