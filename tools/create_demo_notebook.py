                    "    mae = np.mean(np.abs(preds_real - trues_real))\n",
                    "    mape = np.mean(np.abs((preds_real - trues_real) / trues_real)) * 100\n",
                    "    \n",
                    "    # Directional Accuracy\n",
                    "    prev_real = trues_real[:-1]\n",
                    "    da = np.mean((preds_real[1:] - prev_real > 0) == (trues_real[1:] - prev_real > 0)) * 100\n",
                    "    \n",
                    "    # Financial Backtest (Khấu trừ phí 0.1% + trượt giá 0.05%)\n",
                    "    signals = np.where(preds_real[1:] > prev_real, 1, 0) # 1: Long, 0: Cash\n",
